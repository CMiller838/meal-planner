#!/usr/bin/env python3
"""Build cofid.json from the CoFID 2021 xlsx: only the foods tools/cofid-map.json names.
Usage: cofid_build.py <xlsx> [--out cofid.json]. Stdlib only. Exits 1 on header drift or an unknown food code."""
import json, re, sys, zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

N = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
# sheet name -> { CoFID column code (row 2 of the sheet): planner key }
SHEETS = {
    "1.3 Proximates": {"KCALS": "energy_kcal", "PROT": "protein_g", "CHO": "carbohydrate_g", "FAT": "fat_g",
                       "SATFOD": "saturates_g", "AOACFIB": "fibre_g", "TOTSUG": "sugars_g"},
    "1.4 Inorganics": {"NA": "sodium_mg", "K": "potassium_mg", "CA": "calcium_mg", "MG": "magnesium_mg",
                       "FE": "iron_mg", "ZN": "zinc_mg"},
    "1.5 Vitamins": {"RETEQU": "vitA_mcg", "VITD": "vitD_mcg", "VITB12": "vitB12_mcg", "FOLT": "folate_mcg", "VITC": "vitC_mg"},
}
ATTRIBUTION = ("Contains public sector information licensed under the Open Government Licence v3.0. Source: "
               "McCance and Widdowson's The Composition of Foods Integrated Dataset 2021.")


def col(ref):
    return re.sub(r"\d", "", ref)


def read(z, ss, path):
    for r in ET.fromstring(z.read(path)).iter(N + "row"):
        d = {}
        for c in r.iter(N + "c"):
            v = c.find(N + "v")
            if v is not None:
                d[col(c.get("r"))] = ss[int(v.text)] if c.get("t") == "s" else v.text
        yield d


def main():
    args = sys.argv[1:]
    out = Path(args[args.index("--out") + 1]) if "--out" in args else Path("cofid.json")
    z = zipfile.ZipFile(args[0])
    ss = ["".join(t.text or "" for t in si.iter(N + "t")) for si in ET.fromstring(z.read("xl/sharedStrings.xml")).iter(N + "si")]
    wb = ET.fromstring(z.read("xl/workbook.xml"))
    rels = {r.get("Id"): r.get("Target") for r in ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))}
    rid = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
    path = {s.get("name"): "xl/" + rels[s.get(rid)].lstrip("/").removeprefix("xl/") for s in wb.iter(N + "sheet")}
    cmap = json.loads((Path(__file__).parent / "cofid-map.json").read_text())
    codes = {c for e in cmap.values() for c in e.values()}
    foods = {c: {"nutrients": {}} for c in codes}
    errs = []
    for sheet, cols in SHEETS.items():
        rows = list(read(z, ss, path[sheet]))
        hdr = next((r for r in rows[:5] if r.get("A") != "Food Code" and r.get("J") and not r.get("A")), None)
        have = {v: k for k, v in (hdr or {}).items()}
        letters = {}
        for cc, key in cols.items():
            if cc in have:
                letters[key] = have[cc]
            else:
                errs.append(f"{sheet}: column code {cc} not found")
        seen = set()
        for r in rows:
            c = r.get("A")
            if c in foods:
                seen.add(c)
                foods[c].setdefault("name", r.get("B"))
                for key, L in letters.items():
                    v = r.get(L)
                    if v is None or v.strip() in ("", "N"):
                        continue
                    foods[c]["nutrients"][key] = 0 if v.strip() == "Tr" else round(float(v), 3)
        errs += [f"{sheet}: food code {c} not found" for c in sorted(codes - seen)]
    if errs:
        print("\n".join(errs), file=sys.stderr)
        sys.exit(1)
    data = {"_attribution": ATTRIBUTION, "_source": "UK CoFID 2021, per 100 g edible portion. Generated by tools/cofid_build.py; do not hand-edit.",
            "map": cmap, "foods": dict(sorted(foods.items()))}
    out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {out}: {len(foods)} foods")


if __name__ == "__main__":
    main()
